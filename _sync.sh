## 分行业痛点详情

### 医疗（T0）
- 痛点：病历「数据不出院」硬门槛（个保法/数据安全法/等保）；《互联网诊疗监管细则》严禁 AI 自动生成处方，须院内可控可审计；病历质控/DRG 控费/导诊是高频场景
- 采购实据：石河子大学一附院 134.8 万；神木大柳塔 562 万；临汾人民医院 1569 万；数十家公立医院 2025 上半年密集部署 DeepSeek
- 夹层：民营诊所/基层付不起百万级 → 5–20 万轻量一体机/服务空间

### 金融（T0，付费能力最强）
- 痛点：监管数据不出域/不出境；投研研报生成+合规审核是公募第一场景；智能客服是银行采购主力
- 实据：2025 金融大模型中标项目数 +341%、金额 +527%；十余家公募私有化部署 DeepSeek；邮储银行语音客服大模型中标
- 夹层客户画像（对我们最精准）：城商行/农商行/小贷——监管要求私有化但买不起大厂数百万方案

### 法律（T2）
- 痛点：客户数据泄露是第一顾虑（律所不敢用）；中型所每周审 30+ 份×80 页合同；合同审查/文书起草高频
- 形态：7B–14B 小模型+RAG 合同库；中小律所只接受 5–15 万方案

### 政务/国企（T0）
- 痛点：数据不出域+信创环境适配是采购前置；国资委「AI+」专项行动强推（接入大模型从选择题变任务）
- 实据：深圳全市政务云信创部署 DeepSeek；2025 亿元级大单政务占半；华润私有化供下属企业用
- 注意：被电信/华为/浪潮集成商主导，独立服务商切「信创环境适配与运维」缝隙

### 教育（T1）
- 痛点：学生数据不出校；批改/错题归因/个性化是培训机构刚需；按调用计费成本高
- 实据：西南财大 770.75 万采购私有化一体机

### 制造业（T1）
- 痛点：工艺参数/图纸核心机密+车间常物理断网；质检与预测性维护（某车企私有化后准确率 72%→89%）；老师傅工艺知识流失→知识库+维修 Copilot
- 驱动：保密+内网隔离+边缘实时（质检毫秒级延迟云 API 做不到）

### 软件开发/IT（T1）
- 痛点：代码上传公有 API=核心资产外泄（金融央企研发部禁用公有 Copilot 是普遍内规）；内部知识库/RAG 第二大场景
- 形态：IT 自己有运维能力，卖「纯软件+授权」比一体机合适

### MCN/自媒体（T2）
- 痛点：批量内容生产（某 MCN 月产 500 条、单月橱窗佣金 4 万+）；数字人形象/声音克隆是核心资产怕被盗用
- 判断：无合规压力，卖点是成本与定制化；头部 10–50 万定制，腰部以下只买 SaaS

### 电商/跨境（T3）
- 痛点：客服人力成本高（RAG 客服宣称降 70%，低可信）；多语言客服与文案本地化
- 判断：弱私有化行业，只做头部品牌方

### 房地产/本地生活（T3）
- 痛点：获客转化率（麦田系统 +20–30%）；购房者已在大模型里搜楼盘（GEO 趋势）
- 判断：私有化诉求最弱，不建议作为目标

