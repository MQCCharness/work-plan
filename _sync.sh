## 给创业者的三条结论（推断）

1. 最甜夹层：T0 行业里「必须私有化但付不起大厂数百万方案」的中小机构（城商行/农商行、民营医院/连锁诊所、市属国企），预算 5–50 万；差异化在芯片适配成本与行业知识库交付
2. 合规话术即获客话术：医疗「数据不出院」、金融「数据不出域不出境」、政务「信创适配」是采购文件原文级表述，方案包直接对标这些词（附等保/密评/信创清单）比讲模型参数有效
3. 警惕坑：一体机 2025 已过热、价格缩水（钛媒体 2025-10）；纯卖硬件陷价格战，软件+运维+行业模板的持续订阅才是毛利所在

